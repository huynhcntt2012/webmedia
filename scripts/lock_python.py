"""Snapshot installed dependency closures for this Python 3.12 Windows/Linux project.

Run after installing backend[test] in an isolated venv. Both target environments
are checked; missing dependencies fail instead of producing an incomplete lock.
This pins versions, not artifact hashes. Re-run tests and pip-audit after updates.
"""

from importlib import metadata
from pathlib import Path

import tomllib
from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]


def snapshot(roots: list[str]) -> str:
    pending = [Requirement(root) for root in roots]
    seen: set[tuple[str, tuple[str, ...]]] = set()
    pinned: dict[str, str] = {}
    targets = [
        default_environment() | {"sys_platform": system, "platform_system": name}
        for system, name in (("win32", "Windows"), ("linux", "Linux"))
    ]
    while pending:
        requirement = pending.pop()
        key = (canonicalize_name(requirement.name), tuple(sorted(requirement.extras)))
        distribution = metadata.distribution(requirement.name)
        if not requirement.specifier.contains(distribution.version):
            raise RuntimeError(
                f"Installed {requirement.name} violates {requirement.specifier}"
            )
        if key in seen:
            continue
        seen.add(key)
        pinned[key[0]] = distribution.version
        for child in distribution.requires or []:
            dependency = Requirement(child)
            if dependency.marker is None or any(
                dependency.marker.evaluate(target | {"extra": extra})
                for target in targets
                for extra in ("", *requirement.extras)
            ):
                pending.append(dependency)
    return (
        "# Generated by scripts/lock_python.py; Python 3.12, Windows/Linux.\n"
        + "".join(f"{name}=={version}\n" for name, version in sorted(pinned.items()))
    )


def main() -> None:
    project = tomllib.loads((ROOT / "backend/pyproject.toml").read_text())["project"]
    for suffix, roots in (
        ("", project["dependencies"]),
        ("-test", project["dependencies"] + project["optional-dependencies"]["test"]),
    ):
        output = ROOT / f"backend/requirements{suffix}.lock"
        output.write_text(snapshot(roots), encoding="utf-8")
        print(f"Wrote {output.name}")


if __name__ == "__main__":
    main()
